import type { ModuleContract, SchemaField } from '@fable/contracts';

export interface GeneratedAdapterCode {
  contractId: string;
  contractVersion: string;
  sourceCode: string;
  inputValidatorName: string;
  outputValidatorName: string;
}

export class DeterministicAdapterBuilder {
  /**
   * Generates strictly schema-conforming TypeScript adapter code
   * from an approved ModuleContract with zero freehand logic.
   */
  public static generateAdapter(contract: ModuleContract): GeneratedAdapterCode {
    const inputZodFields = this.buildZodFields(contract.inputs);
    const outputZodFields = this.buildZodFields(contract.outputs);

    const inputValidatorName = `${this.toPascalCase(contract.name)}InputSchema`;
    const outputValidatorName = `${this.toPascalCase(contract.name)}OutputSchema`;
    const inputTypeName = `${this.toPascalCase(contract.name)}Input`;
    const outputTypeName = `${this.toPascalCase(contract.name)}Output`;

    const code = `/**
 * AUTO-GENERATED BY FABLE ENGINE v3 DETERMINISTIC BUILDER (TIER 2)
 * CONTRACT: ${contract.id} (Version: ${contract.version})
 * DO NOT EDIT MANUALLY. CONTAINS ZERO FREEHAND LOGIC.
 */

import { z } from 'zod';

export const ${inputValidatorName} = z.object({
${inputZodFields}
});

export const ${outputValidatorName} = z.object({
${outputZodFields}
});

export type ${inputTypeName} = z.infer<typeof ${inputValidatorName}>;
export type ${outputTypeName} = z.infer<typeof ${outputValidatorName}>;

export interface ${this.toPascalCase(contract.name)}Handler {
  execute(input: ${inputTypeName}): Promise<${outputTypeName}>;
}

export class ${this.toPascalCase(contract.name)}Adapter {
  private readonly handler: ${this.toPascalCase(contract.name)}Handler;

  constructor(handler: ${this.toPascalCase(contract.name)}Handler) {
    this.handler = handler;
  }

  public async run(rawInput: unknown): Promise<${outputTypeName}> {
    // 1. Ingress schema validation (blocking)
    const validatedInput = ${inputValidatorName}.parse(rawInput);

    // 2. Invoke module implementation
    const rawOutput = await this.handler.execute(validatedInput);

    // 3. Egress schema validation (blocking)
    return ${outputValidatorName}.parse(rawOutput);
  }
}
`;

    return {
      contractId: contract.id,
      contractVersion: contract.version,
      sourceCode: code,
      inputValidatorName,
      outputValidatorName,
    };
  }

  private static buildZodFields(fields: Record<string, SchemaField>): string {
    const entries = Object.entries(fields);
    if (entries.length === 0) {
      return '  // No fields declared';
    }

    return entries
      .map(([key, field]) => {
        let zodType = 'z.unknown()';
        if (field.type === 'string') zodType = 'z.string()';
        else if (field.type === 'number') zodType = 'z.number()';
        else if (field.type === 'boolean') zodType = 'z.boolean()';
        else if (field.type === 'array') zodType = 'z.array(z.unknown())';
        else if (field.type === 'object') zodType = 'z.record(z.string(), z.unknown())';

        if (!field.required) {
          zodType += '.optional()';
        }

        const comment = field.description ? `  /** ${field.description} */\n` : '';
        return `${comment}  ${key}: ${zodType},`;
      })
      .join('\n');
  }

  private static toPascalCase(str: string): string {
    return str
      .replace(/[-_](\w)/g, (_, c) => c.toUpperCase())
      .replace(/^\w/, c => c.toUpperCase());
  }
}
